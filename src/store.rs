//! Agent records on disk: one JSON file per agent, mode 0600, in a 0700
//! directory owned by the signer's own system user.

use std::fs::{self, OpenOptions};
use std::io::Write;
use std::os::unix::fs::{OpenOptionsExt, PermissionsExt};
use std::path::{Path, PathBuf};

use anyhow::{Context, Result, anyhow, bail};
use ed25519_dalek::SigningKey;
use serde::{Deserialize, Serialize};
use zeroize::{Zeroize, ZeroizeOnDrop};

pub const DEFAULT_METHODS: &[&str] = &[
    "prepare",
    "authorize",
    "cancel_prepared",
    "cancel_nonce",
    "renounce_role",
];
/// 300 Tgas: the protocol maximum for one transaction.
pub const DEFAULT_MAX_GAS: u64 = 300_000_000_000_000;

#[derive(Clone, Serialize, Deserialize, Zeroize, ZeroizeOnDrop)]
pub struct ApiAccess {
    pub url: String,
    pub key: String,
}

#[derive(Clone, Serialize, Deserialize, Zeroize, ZeroizeOnDrop)]
pub struct AgentRecord {
    pub account_id: String,
    pub network_id: String,
    /// The only contract this agent's key may call.
    pub vault_id: String,
    pub allowed_methods: Vec<String>,
    pub max_gas: u64,
    /// Largest attached deposit, in yoctoNEAR, as a decimal string.
    pub max_deposit_yocto: String,
    /// ed25519 secret seed, base58, 32 bytes.
    secret_seed: String,
    /// A key generated by `rotate`, signing only after `promote`.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    next_secret_seed: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub api: Option<ApiAccess>,
}

fn decode_seed(seed: &str) -> Result<SigningKey> {
    let mut bytes = bs58::decode(seed)
        .into_vec()
        .context("seed is not base58")?;
    let array: [u8; 32] = bytes
        .as_slice()
        .try_into()
        .map_err(|_| anyhow!("seed must be 32 bytes"))?;
    bytes.zeroize();
    Ok(SigningKey::from_bytes(&array))
}

fn new_seed() -> String {
    let mut bytes = [0u8; 32];
    getrandom::fill(&mut bytes).expect("the operating system's random source is unavailable");
    let seed = bs58::encode(bytes).into_string();
    bytes.zeroize();
    seed
}

pub fn near_public_key(key: &SigningKey) -> String {
    format!(
        "ed25519:{}",
        bs58::encode(key.verifying_key().to_bytes()).into_string()
    )
}

impl AgentRecord {
    pub fn new(
        account_id: &str,
        network_id: &str,
        vault_id: &str,
        methods: Vec<String>,
        api: Option<ApiAccess>,
    ) -> Self {
        AgentRecord {
            account_id: account_id.to_owned(),
            network_id: network_id.to_owned(),
            vault_id: vault_id.to_owned(),
            allowed_methods: methods,
            max_gas: DEFAULT_MAX_GAS,
            max_deposit_yocto: "1".to_owned(),
            secret_seed: new_seed(),
            next_secret_seed: None,
            api,
        }
    }

    pub fn signing_key(&self) -> Result<SigningKey> {
        decode_seed(&self.secret_seed)
    }

    pub fn public_key(&self) -> Result<String> {
        Ok(near_public_key(&self.signing_key()?))
    }

    pub fn next_public_key(&self) -> Result<Option<String>> {
        self.next_secret_seed
            .as_deref()
            .map(|seed| decode_seed(seed).map(|key| near_public_key(&key)))
            .transpose()
    }

    pub fn max_deposit(&self) -> Result<u128> {
        self.max_deposit_yocto.parse().context("max_deposit_yocto")
    }

    pub fn rotate(&mut self) {
        self.next_secret_seed = Some(new_seed());
    }

    pub fn promote(&mut self) -> Result<()> {
        let next = self
            .next_secret_seed
            .take()
            .ok_or_else(|| anyhow!("no rotated key to promote: run `rotate` first"))?;
        self.secret_seed = next;
        Ok(())
    }
}

pub fn valid_account_id(id: &str) -> bool {
    (2..=64).contains(&id.len())
        && id.bytes().all(|b| {
            b.is_ascii_lowercase() || b.is_ascii_digit() || matches!(b, b'.' | b'-' | b'_')
        })
        && !id.starts_with('.')
        && !id.contains("..")
}

pub struct Store {
    dir: PathBuf,
}

impl Store {
    pub fn open(state_dir: &Path) -> Result<Store> {
        let dir = state_dir.join("agents");
        fs::create_dir_all(&dir).with_context(|| format!("create {}", dir.display()))?;
        fs::set_permissions(state_dir, fs::Permissions::from_mode(0o700))?;
        fs::set_permissions(&dir, fs::Permissions::from_mode(0o700))?;
        Ok(Store { dir })
    }

    fn path(&self, account_id: &str) -> Result<PathBuf> {
        if !valid_account_id(account_id) {
            bail!("invalid NEAR account id: {account_id}");
        }
        Ok(self.dir.join(format!("{account_id}.json")))
    }

    pub fn load(&self, account_id: &str) -> Result<AgentRecord> {
        let path = self.path(account_id)?;
        let meta = fs::metadata(&path).with_context(|| format!("unknown agent {account_id}"))?;
        if meta.permissions().mode() & 0o077 != 0 {
            bail!(
                "{} is readable by others: refusing to use it (chmod 600)",
                path.display()
            );
        }
        let mut text = fs::read_to_string(&path)?;
        let record = serde_json::from_str(&text).context("agent record is not valid JSON");
        text.zeroize();
        record
    }

    pub fn save(&self, record: &AgentRecord) -> Result<()> {
        let path = self.path(&record.account_id)?;
        let tmp = path.with_extension("json.tmp");
        let mut text = serde_json::to_string_pretty(record)?;
        {
            let mut file = OpenOptions::new()
                .write(true)
                .create(true)
                .truncate(true)
                .mode(0o600)
                .open(&tmp)?;
            file.write_all(text.as_bytes())?;
            file.sync_all()?;
        }
        text.zeroize();
        fs::rename(&tmp, &path)?;
        Ok(())
    }

    pub fn exists(&self, account_id: &str) -> bool {
        self.path(account_id)
            .map(|path| path.exists())
            .unwrap_or(false)
    }

    pub fn remove(&self, account_id: &str) -> Result<()> {
        let path = self.path(account_id)?;
        fs::remove_file(&path).with_context(|| format!("unknown agent {account_id}"))
    }

    pub fn list(&self) -> Result<Vec<String>> {
        let mut out = Vec::new();
        for entry in fs::read_dir(&self.dir)? {
            let name = entry?.file_name().to_string_lossy().into_owned();
            if let Some(account) = name.strip_suffix(".json") {
                out.push(account.to_owned());
            }
        }
        out.sort();
        Ok(out)
    }
}
